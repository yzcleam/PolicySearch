export function parseArgs(argv = process.argv.slice(2)) {
  const args = { _: [] };
  for (let index = 0; index < argv.length; index += 1) {
    const current = argv[index];
    if (current === "--") {
      args._.push(...argv.slice(index + 1));
      break;
    }
    if (!current.startsWith("--")) {
      args._.push(current);
      continue;
    }
    const body = current.slice(2);
    const equal = body.indexOf("=");
    if (equal !== -1) {
      args[body.slice(0, equal)] = body.slice(equal + 1);
      continue;
    }
    const next = argv[index + 1];
    if (next !== undefined && !next.startsWith("--")) {
      args[body] = next;
      index += 1;
    } else {
      args[body] = true;
    }
  }
  return args;
}

export function readEnv(file = ENV_FILE) {
  if (!fs.existsSync(file)) return {};
  const values = {};
  const lines = fs.readFileSync(file, "utf8").split(/\r?\n/);
  for (const raw of lines) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const equal = line.indexOf("=");
    if (equal < 0) continue;
    let key = line.slice(0, equal).trim();
    if (key.startsWith("export ")) key = key.slice(7).trim();
    let value = line.slice(equal + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      const quote = value[0];
      value = value.slice(1, -1);
      if (quote === '"') {
        value = value.replace(/\\n/g, "\n").replace(/\\"/g, '"').replace(/\\\\/g, "\\");
      }
    }
    values[key] = value;
  }
  return values;
}

export function writeEnv(values, file = ENV_FILE) {
  const lines = [
    "# Generated by `npm run deploy`.",
    "# This file contains local secrets and is ignored by git.",
    "",
  ];
  for (const [key, value] of Object.entries(values)) {
    if (value === undefined || value === null) continue;
    let text = String(value);
    if (/[\s#"'$\\]/.test(text)) {
      text = `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
    }
    lines.push(`${key}=${text}`);
  }
  fs.writeFileSync(file, `${lines.join("\n")}\n`, { encoding: "utf8", mode: 0o600 });
  if (!IS_WIN) {
    try {
      fs.chmodSync(file, 0o600);
    } catch {
      // Best effort; some filesystems do not support POSIX modes.
    }
  }
}

export function run(cmd, args = [], options = {}) {
  try {
    const result = spawnSync(cmd, args, {
      cwd: options.cwd ?? ROOT,
      env: options.env ?? process.env,
      encoding: "utf8",
      timeout: options.timeout ?? 120_000,
      windowsHide: true,
      stdio: ["ignore", "pipe", "pipe"],
    });
    return {
      ok: result.status === 0,
      code: result.status,
      signal: result.signal,
      stdout: result.stdout ?? "",
      stderr: result.stderr ?? "",
      error: result.error,
    };
  } catch (error) {
    return { ok: false, code: null, stdout: "", stderr: "", error };
  }
}

export function runStream(cmd, args = [], options = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(cmd, args, {
      cwd: options.cwd ?? ROOT,
      env: options.env ?? process.env,
      stdio: "inherit",
      windowsHide: false,
    });
    child.once("error", reject);
    child.once("exit", (code, signal) => resolve({ code, signal }));
  });
}

export async function runStreamChecked(cmd, args = [], options = {}) {
  const result = await runStream(cmd, args, options);
  if (result.code !== 0) {
    throw new Error(`命令执行失败 (${result.code}): ${cmd} ${args.join(" ")}`);
  }
  return result;
}

